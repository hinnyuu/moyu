"""Local filesystem storage and SQLite metadata.

The data root is supplied by configuration. Layout::

    <dataRoot>/uploads/<session-id>/data
    <dataRoot>/assets/<asset-id>
    <dataRoot>/jobs/<job-id>/
    <dataRoot>/outputs/<job-id>/<name>
    <dataRoot>/preview/<asset-id>/<profile>/
    <dataRoot>/state.db

IDs are generated by this module, never taken from user input, so paths cannot
escape the data root.
"""

import datetime as dt
import hashlib
import json
import os
import shutil
import sqlite3
import time
import uuid
from dataclasses import dataclass
from pathlib import Path

from .errors import StorageError

JOB_STATUSES = ("created", "queued", "running", "verifying", "succeeded", "failed", "canceled")
FINAL_STATUSES = ("succeeded", "failed", "canceled")
TRANSITIONS = {
    "created": {"queued", "canceled"},
    "queued": {"running", "canceled"},
    "running": {"verifying", "failed", "canceled"},
    "verifying": {"succeeded", "failed"},
    "succeeded": set(),
    "failed": set(),
    "canceled": set(),
}


def _now():
    return dt.datetime.now(dt.timezone.utc).isoformat()


def _new_id():
    return uuid.uuid4().hex


def _sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        while True:
            chunk = handle.read(1024 * 1024)
            if not chunk:
                break
            digest.update(chunk)
    return digest.hexdigest()


@dataclass
class Asset:
    id: str
    original_name: str
    path: str
    size: int
    sha256: str
    media_type: str
    created_at: str


@dataclass
class Job:
    id: str
    status: str
    request: dict
    progress: int
    error: str
    created_at: str
    updated_at: str


class Storage:
    def __init__(self, data_root, quota_bytes=0):
        self.data_root = Path(data_root).resolve()
        self.quota_bytes = int(quota_bytes)
        self.db_path = self.data_root / "state.db"
        self.uploads_dir = self.data_root / "uploads"
        self.assets_dir = self.data_root / "assets"
        self.jobs_dir = self.data_root / "jobs"
        self.outputs_dir = self.data_root / "outputs"
        self.preview_dir = self.data_root / "preview"

    def ensure_layout(self):
        try:
            for directory in (
                self.data_root,
                self.uploads_dir,
                self.assets_dir,
                self.jobs_dir,
                self.outputs_dir,
                self.preview_dir,
            ):
                directory.mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            raise StorageError("storage_unwritable", f"无法创建数据目录: {exc}") from exc
        with self.connect() as conn:
            conn.executescript(
                """
                CREATE TABLE IF NOT EXISTS assets (
                    id TEXT PRIMARY KEY,
                    original_name TEXT NOT NULL,
                    path TEXT NOT NULL,
                    size INTEGER NOT NULL,
                    sha256 TEXT NOT NULL,
                    media_type TEXT NOT NULL,
                    created_at TEXT NOT NULL
                );
                CREATE TABLE IF NOT EXISTS jobs (
                    id TEXT PRIMARY KEY,
                    status TEXT NOT NULL,
                    request TEXT NOT NULL,
                    progress INTEGER NOT NULL DEFAULT 0,
                    error TEXT NOT NULL DEFAULT '',
                    created_at TEXT NOT NULL,
                    updated_at TEXT NOT NULL
                );
                CREATE TABLE IF NOT EXISTS job_events (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    job_id TEXT NOT NULL,
                    event TEXT NOT NULL,
                    created_at TEXT NOT NULL
                );
                CREATE TABLE IF NOT EXISTS upload_sessions (
                    id TEXT PRIMARY KEY,
                    filename TEXT NOT NULL,
                    size INTEGER NOT NULL,
                    offset INTEGER NOT NULL DEFAULT 0,
                    status TEXT NOT NULL,
                    created_at TEXT NOT NULL,
                    updated_at TEXT NOT NULL
                );
                """
            )
        return self

    def connect(self):
        deadline = time.monotonic() + 30
        while True:
            conn = None
            try:
                conn = sqlite3.connect(self.db_path, timeout=30)
                conn.row_factory = sqlite3.Row
                conn.execute("PRAGMA busy_timeout=30000")
                conn.execute("PRAGMA journal_mode=WAL")
                conn.execute("PRAGMA foreign_keys=ON")
                return _Connection(conn)
            except sqlite3.OperationalError as exc:
                if conn is not None:
                    conn.close()
                if "locked" in str(exc).lower() and time.monotonic() < deadline:
                    time.sleep(0.1)
                    continue
                raise StorageError(
                    "storage_unavailable", f"无法初始化数据库: {exc}"
                ) from exc
            except sqlite3.Error as exc:
                if conn is not None:
                    conn.close()
                raise StorageError(
                    "storage_unavailable", f"无法打开数据库: {exc}"
                ) from exc

    def _under(self, base, child):
        candidate = (base / child).resolve()
        try:
            candidate.relative_to(self.data_root)
        except ValueError as exc:
            raise StorageError("path_escape", "路径越出数据根目录") from exc
        return candidate

    def upload_path(self, session_id):
        return self._under(self.uploads_dir, Path(str(session_id)) / "data")

    def asset_path(self, asset_id):
        return self._under(self.assets_dir, str(asset_id))

    def job_dir(self, job_id):
        return self._under(self.jobs_dir, str(job_id))

    def output_path(self, job_id, name):
        name = Path(str(name)).name
        if not name or name in (".", ".."):
            raise StorageError("path_escape", "输出文件名非法")
        return self._under(self.outputs_dir / str(job_id), name)

    def preview_path(self, asset_id, profile):
        profile = Path(str(profile)).name
        if not profile or profile in (".", ".."):
            raise StorageError("path_escape", "预览 profile 非法")
        return self._under(self.preview_dir / str(asset_id), profile)

    def used_bytes(self):
        total = 0
        for base in (
            self.uploads_dir,
            self.assets_dir,
            self.jobs_dir,
            self.outputs_dir,
            self.preview_dir,
        ):
            if not base.exists():
                continue
            for root, _dirs, files in os.walk(base):
                for name in files:
                    try:
                        total += os.path.getsize(os.path.join(root, name))
                    except OSError:
                        continue
        return total

    def check_quota(self, additional=0):
        if self.quota_bytes <= 0:
            return
        used = self.used_bytes()
        if used + int(additional) > self.quota_bytes:
            raise StorageError(
                "quota_exceeded",
                "存储配额不足",
                [f"used={used}", f"additional={additional}", f"quota={self.quota_bytes}"],
            )

    def cleanup(self, upload_ttl_seconds=None, preview_ttl_seconds=None):
        removed = {"uploads": 0, "previews": 0}
        now = dt.datetime.now(dt.timezone.utc).timestamp()
        if upload_ttl_seconds is not None:
            with self.connect() as conn:
                rows = conn.execute(
                    "SELECT id, updated_at FROM upload_sessions"
                ).fetchall()
                for row in rows:
                    try:
                        updated = dt.datetime.fromisoformat(row["updated_at"]).timestamp()
                    except ValueError:
                        continue
                    if now - updated >= upload_ttl_seconds:
                        session_dir = self.uploads_dir / row["id"]
                        if session_dir.exists():
                            shutil.rmtree(session_dir, ignore_errors=True)
                        conn.execute(
                            "DELETE FROM upload_sessions WHERE id=?", (row["id"],)
                        )
                        removed["uploads"] += 1
        if preview_ttl_seconds is not None and self.preview_dir.exists():
            for asset_dir in list(self.preview_dir.iterdir()):
                if not asset_dir.is_dir():
                    continue
                for profile_dir in list(asset_dir.iterdir()):
                    if not profile_dir.is_dir():
                        continue
                    try:
                        age = now - profile_dir.stat().st_mtime
                    except OSError:
                        continue
                    if age >= preview_ttl_seconds:
                        shutil.rmtree(profile_dir, ignore_errors=True)
                        removed["previews"] += 1
                try:
                    if not any(asset_dir.iterdir()):
                        asset_dir.rmdir()
                except OSError:
                    pass
        return removed


class _Connection:
    def __init__(self, conn):
        self._conn = conn

    def __enter__(self):
        return self._conn

    def __exit__(self, exc_type, exc, tb):
        if exc_type is None:
            self._conn.commit()
        else:
            self._conn.rollback()
        self._conn.close()
        return False


class AssetStore:
    def __init__(self, storage):
        self.storage = storage
        self.storage.ensure_layout()

    def register_asset(self, source_path, original_name=None, media_type="application/octet-stream"):
        source = Path(source_path)
        if not source.is_file():
            raise StorageError("asset_missing", f"源文件不存在: {source}")
        size = source.stat().st_size
        self.storage.check_quota(size)
        asset_id = _new_id()
        destination = self.storage.asset_path(asset_id)
        try:
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(source), str(destination))
        except OSError as exc:
            raise StorageError("asset_write_failed", f"登记资产失败: {exc}") from exc
        now = _now()
        asset = Asset(
            id=asset_id,
            original_name=original_name or source.name,
            path=str(destination),
            size=size,
            sha256=_sha256(destination),
            media_type=media_type,
            created_at=now,
        )
        with self.storage.connect() as conn:
            conn.execute(
                "INSERT INTO assets (id, original_name, path, size, sha256, media_type, created_at)"
                " VALUES (?, ?, ?, ?, ?, ?, ?)",
                (
                    asset.id,
                    asset.original_name,
                    asset.path,
                    asset.size,
                    asset.sha256,
                    asset.media_type,
                    asset.created_at,
                ),
            )
        return asset

    def get_asset(self, asset_id):
        with self.storage.connect() as conn:
            row = conn.execute(
                "SELECT * FROM assets WHERE id=?", (str(asset_id),)
            ).fetchone()
        if row is None:
            raise StorageError("asset_not_found", f"资产不存在: {asset_id}")
        return Asset(
            id=row["id"],
            original_name=row["original_name"],
            path=row["path"],
            size=row["size"],
            sha256=row["sha256"],
            media_type=row["media_type"],
            created_at=row["created_at"],
        )

    def path_for(self, asset_id):
        asset = self.get_asset(asset_id)
        path = Path(asset.path).resolve()
        try:
            path.relative_to(self.storage.data_root)
        except ValueError as exc:
            raise StorageError("path_escape", "资产路径越出数据根目录") from exc
        return path

    def open_asset(self, asset_id):
        return open(self.path_for(asset_id), "rb")

    def list_assets(self, limit=100):
        with self.storage.connect() as conn:
            rows = conn.execute(
                "SELECT * FROM assets ORDER BY created_at DESC LIMIT ?", (int(limit),)
            ).fetchall()
        return [
            Asset(
                id=row["id"],
                original_name=row["original_name"],
                path=row["path"],
                size=row["size"],
                sha256=row["sha256"],
                media_type=row["media_type"],
                created_at=row["created_at"],
            )
            for row in rows
        ]

    def delete_asset(self, asset_id):
        asset = self.get_asset(asset_id)
        path = self.storage.asset_path(asset.id)
        try:
            if path.exists():
                path.unlink()
        except OSError as exc:
            raise StorageError("asset_delete_failed", f"删除资产失败: {exc}") from exc
        with self.storage.connect() as conn:
            conn.execute("DELETE FROM assets WHERE id=?", (asset.id,))
        return True


class JobStore:
    def __init__(self, storage):
        self.storage = storage
        self.storage.ensure_layout()

    def create_job(self, request):
        job_id = _new_id()
        now = _now()
        with self.storage.connect() as conn:
            conn.execute(
                "INSERT INTO jobs (id, status, request, progress, error, created_at, updated_at)"
                " VALUES (?, 'created', ?, 0, '', ?, ?)",
                (job_id, json.dumps(request, ensure_ascii=False), now, now),
            )
        return self.get_job(job_id)

    def get_job(self, job_id):
        with self.storage.connect() as conn:
            row = conn.execute("SELECT * FROM jobs WHERE id=?", (str(job_id),)).fetchone()
        if row is None:
            raise StorageError("job_not_found", f"任务不存在: {job_id}")
        return self._row_to_job(row)

    def _row_to_job(self, row):
        return Job(
            id=row["id"],
            status=row["status"],
            request=json.loads(row["request"]),
            progress=row["progress"],
            error=row["error"],
            created_at=row["created_at"],
            updated_at=row["updated_at"],
        )

    def list_jobs(self, status=None, limit=100):
        query = "SELECT * FROM jobs"
        params = []
        if status is not None:
            query += " WHERE status=?"
            params.append(status)
        query += " ORDER BY created_at DESC LIMIT ?"
        params.append(int(limit))
        with self.storage.connect() as conn:
            rows = conn.execute(query, params).fetchall()
        return [self._row_to_job(row) for row in rows]

    def claim_next(self):
        now = _now()
        with self.storage.connect() as conn:
            row = conn.execute(
                "SELECT id FROM jobs WHERE status='queued' ORDER BY created_at LIMIT 1"
            ).fetchone()
            if row is None:
                return None
            changed = conn.execute(
                "UPDATE jobs SET status='running', updated_at=? WHERE id=? AND status='queued'",
                (now, row["id"]),
            ).rowcount
        if changed != 1:
            return None
        return self.get_job(row["id"])

    def recover_stale(self):
        now = _now()
        with self.storage.connect() as conn:
            changed = conn.execute(
                "UPDATE jobs SET status='queued', error=?, updated_at=?"
                " WHERE status IN ('running', 'verifying')",
                ("worker restarted; requeued", now),
            ).rowcount
        return changed

    def update_status(self, job_id, status, progress=None, error=None):
        if status not in JOB_STATUSES:
            raise StorageError("job_status_invalid", f"未知任务状态: {status}")
        job = self.get_job(job_id)
        if status != job.status and status not in TRANSITIONS[job.status]:
            raise StorageError(
                "job_transition_invalid",
                f"任务状态不能从 {job.status} 变为 {status}",
            )
        progress_value = job.progress if progress is None else max(0, min(100, int(progress)))
        if status in FINAL_STATUSES:
            progress_value = 100 if status == "succeeded" else progress_value
        error_value = job.error if error is None else str(error)
        now = _now()
        with self.storage.connect() as conn:
            conn.execute(
                "UPDATE jobs SET status=?, progress=?, error=?, updated_at=? WHERE id=?",
                (status, progress_value, error_value, now, job.id),
            )
        return self.get_job(job.id)

    def cancel_job(self, job_id):
        job = self.get_job(job_id)
        if job.status in FINAL_STATUSES:
            return job
        if "canceled" not in TRANSITIONS[job.status]:
            raise StorageError(
                "job_transition_invalid", f"任务状态不能从 {job.status} 取消"
            )
        return self.update_status(job.id, "canceled")

    def append_event(self, job_id, event):
        self.get_job(job_id)
        with self.storage.connect() as conn:
            conn.execute(
                "INSERT INTO job_events (job_id, event, created_at) VALUES (?, ?, ?)",
                (str(job_id), json.dumps(event, ensure_ascii=False), _now()),
            )

    def events(self, job_id, limit=1000):
        with self.storage.connect() as conn:
            rows = conn.execute(
                "SELECT event, created_at FROM job_events WHERE job_id=? ORDER BY id LIMIT ?",
                (str(job_id), int(limit)),
            ).fetchall()
        return [
            {"event": json.loads(row["event"]), "created_at": row["created_at"]}
            for row in rows
        ]